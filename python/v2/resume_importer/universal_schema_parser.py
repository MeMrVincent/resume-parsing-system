                # 清洗公司名称前缀词与时间后缀（如 贝克曼库尔特...有限公司 (1年5个月)）
                # EN: Clean prefix words and time suffixes from the company name (e.g. 贝克曼库尔特...有限公司 (1年5个月))
                # JA: 会社名から接頭語と期間の接尾辞を除去する（例：贝克曼库尔特...有限公司 (1年5个月)）
                company_name = re.sub(r"^(?:公司|单位|名称|所属单位)[:：\s]*", "", company_name).strip()
