    def _extract_languages(self, text: str) -> list[dict[str, Any]]:
        langs = []

        # 匹配 ▲技能/语言 区域中的 英语 一般
        # EN: Match 英语 一般 (English, basic) in the ▲技能/语言 (skills/language) area
        # JA: ▲技能/语言（スキル／語学）欄の 英语 一般（英語・普通）にマッチする
        m_eng = re.search(r"英\s*语\s*[:：\t\s\n]*([^\n]+)", text)
        if m_eng:
            l_val = m_eng.group(1).strip()
            if l_val:
                langs.append({"language_name": "英语", "language_level": l_val[:20], "language_certificate": "有", "language_certificate_time": ""})

        # 日语：尝试提取 N1/N2 分数（如「141/180点」）
        # EN: Japanese: try extracting the N1/N2 score (e.g. 「141/180点」)
        # JA: 日本語：N1/N2 の点数の抽出を試みる（例：「141/180点」）
        m_n1 = re.search(r"(?:日语一級|日本語1級|JLPT N1|\bN1\b|日语国际一级|日本語能力試験N1)[^\n]*(\d{2,3}/\d{2,3}点?)?", text)
        m_n2 = re.search(r"(?:日语二级|日本語2級|JLPT N2|\bN2\b)[^\n]*(\d{2,3}/\d{2,3}点?)?", text)
        if m_n1:
            score = m_n1.group(1) or ""
            level = f"N1精通（{score}）" if score else "N1精通"
            langs.append({"language_name": "日语", "language_level": level, "language_certificate": "有", "language_certificate_time": ""})
        elif m_n2:
            score = m_n2.group(1) or ""
            level = f"N2（{score}）" if score else "N2"
            langs.append({"language_name": "日语", "language_level": level, "language_certificate": "有", "language_certificate_time": ""})

        # 英语：优先提取 TOEIC 分数，其次 CET 等级
        # EN: English: prefer extracting the TOEIC score, then the CET level
        # JA: 英語：TOEIC の点数を優先して抽出し、次に CET のレベル
        if not langs:
            m_toeic = re.search(r"TOEIC[^\n]*(\d{3,4}/\d{3,4}点?)?", text)
            if m_toeic:
                score = m_toeic.group(1) or ""
                cet6 = "・CET-6" if re.search(r"英语六级|CET6|CET-6|大学英语六级|大学英語六級", text) else ""
                level = f"TOEIC（{score}）{cet6}" if score else f"TOEIC{cet6}"
                langs.append({"language_name": "英语", "language_level": level, "language_certificate": "有", "language_certificate_time": ""})
            elif re.search(r"英语六级|CET6|CET-6|大学英语六级|大学英語六級", text):
                langs.append({"language_name": "英语", "language_level": "CET-6", "language_certificate": "有", "language_certificate_time": ""})
            elif re.search(r"英语四级|CET4|CET-4|英語四級", text):
                langs.append({"language_name": "英语", "language_level": "CET-4", "language_certificate": "有", "language_certificate_time": ""})

        return langs

    def _extract_skills(self, text: str) -> list[dict[str, Any]]:
        skills = []
        seen_names = set()

        # 1. 语言能力技能项（对齐 demo.贺俊新 规范）
        # EN: 1. Language-skill items (aligned with the demo.贺俊新 convention)
        # JA: 1. 語学力のスキル項目（demo.贺俊新 の規約に合わせる）
        if re.search(r"日语一級|日本語1級|JLPT N1|\bN1\b|日语国际一级", text):
            skills.append({"skills_name": "日语国际一级", "skills_level": "熟练", "skills_certificate": "有"})
            seen_names.add("日语国际一级")
        elif re.search(r"日语二级|日本語2級|JLPT N2|\bN2\b", text):
            skills.append({"skills_name": "日语二级", "skills_level": "熟练", "skills_certificate": "有"})
            seen_names.add("日语二级")

        if re.search(r"英语六级|CET6|CET-6|大学英语六级", text):
            skills.append({"skills_name": "英语六级", "skills_level": "熟练", "skills_certificate": "有"})
            seen_names.add("英语六级")
        elif re.search(r"英语四级|CET4|CET-4|大学英语四级", text):
            skills.append({"skills_name": "英语四级", "skills_level": "熟练", "skills_certificate": "有"})
            seen_names.add("英语四级")

        # 2. 从技能与专业段落中深加工提纯短技能名词
        # EN: 2. Further refine short skill nouns from the skills and major paragraphs
        # JA: 2. スキルと専攻の段落から短いスキル名詞をさらに精製する
        m = re.search(r"(?:技能专长|IT技能|Skills|计算机水平|パソコン|专业技能)\s*[:：\t\n\s]*([\s\S]{5,800}?)(?=\n\s*(?:外语|个人兴趣|打工|奖惩|研究|自我评价|趣味|项目经历|工作经历|教育经历|附加信息|\Z))", text, re.IGNORECASE)
        if m:
            sec_text = m.group(1)
            lines = [l.strip() for l in sec_text.splitlines() if l.strip()]
            for l in lines:
                if re.search(r"^(?:附加信息|自我评价|工作经历|教育经历|项目经历|个人技能|技能专长|主要工作)$", l):
                    continue
                # 排除带有时间的整行履历
                # EN: Exclude whole history lines that contain dates
                # JA: 日付を含む経歴の行全体を除外する
                if re.search(r"(?:19|20)\d{2}[\./\-年]", l):
                    continue

                l_clean = re.sub(r"^[*\-•\d\.\s]+", "", l).strip()
                if not l_clean: continue

                # 坚决剔除职责动作性口吻 (负责/监督/推动/组织/参与/开展/配合/工作/活动/宣传)
                # EN: Firmly remove duty-like action phrasing (负责/监督/推动/组织/参与/开展/配合/工作/活动/宣传: responsible for/supervise/promote/organise/participate/carry out/cooperate/work/activity/publicity)
                # JA: 職務的な動作の言い回し（负责／监督／推动／组织／参与／开展／配合／工作／活动／宣传：担当・監督・推進・組織・参加・実施・協力・業務・活動・広報）を断固除外する
                if any(action_kw in l_clean for action_kw in ["负责", "监督", "推动", "组织", "参与", "开展", "配合", "宣传", "评价"]):
                    continue

                # 按标点符号与空格切割提纯
                # EN: Split and refine on punctuation and spaces
                # JA: 句読点と空白で分割して精製する
                parts = re.split(r"[:：,，、;；\s]{1,4}", l_clean)
                for p in parts:
                    p_name = p.strip()
                    p_name = re.sub(r"[。\.].*$", "", p_name).strip()
                    p_name = re.sub(r"^(?:精通|熟练|掌握|了解|和)\s*", "", p_name).strip()
                    
                    # 严格过滤非技能名词 (拒绝 '工作'、'实际效果'、'问提反' 等虚词)
                    # EN: Strictly filter non-skill nouns (reject function words such as '工作', '实际效果', '问提反')
                    # JA: スキルでない名詞を厳格に除外する（'工作'、'实际效果'、'问提反' などの虚詞を拒否）
                    if not p_name or len(p_name) > 15 or len(p_name) < 2:
                        continue
                    if any(noise in p_name for noise in ["工作", "活动", "效果", "宣传", "发布", "评价", "提反", "体系", "部门", "公司", "机构", "学校", "专长", "相关", "有关"]):
                        continue

                    if p_name and p_name not in seen_names and not any(c.isdigit() for c in p_name[:3]):
                        seen_names.add(p_name)
                        skills.append({
                            "skills_name": p_name,
                            "skills_level": "熟练",
                            "skills_certificate": "有"
                        })

        if not any("计算机" in s["skills_name"] for s in skills) and re.search(r"Office|Word|Excel|CAD|Solidworks|计算机", text, re.IGNORECASE):
            skills.append({"skills_name": "计算机熟练", "skills_level": "熟练", "skills_certificate": "有"})

        return skills[:10]
